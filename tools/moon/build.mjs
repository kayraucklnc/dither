// The moon's near side as a 256 × 256 greyscale texture, for the moon phase
// widget's pictures drawn when a project compiles. From NASA's Lunar
// Reconnaissance Orbiter mosaic on Wikimedia Commons, which is in the public
// domain: lit evenly, so it is the surface alone and the widget adds the
// shadow. Run by hand; the output is committed: node moon/build.mjs

import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const FILE = "Moon nearside LRO 5000.jpg";
const SIZE = 256;
const UA = { "User-Agent": "dither-moon/1.0 (https://github.com/kayraucklnc/dither)" };

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.resolve(here, "../../app/src/extensions/moon/texture.ts");

const query = new URLSearchParams({
  action: "query", format: "json", titles: `File:${FILE}`,
  prop: "imageinfo", iiprop: "url|extmetadata", iiurlwidth: "1000",
});
const pages = (await (await fetch(`https://commons.wikimedia.org/w/api.php?${query}`, { headers: UA })).json()).query.pages;
const info = Object.values(pages)[0].imageinfo[0];
const licence = info.extmetadata.LicenseShortName?.value ?? "";
if (licence !== "Public domain") throw new Error(`${FILE}: ${JSON.stringify(licence)} is not public domain`);
const jpeg = Buffer.from(await (await fetch(info.thumburl, { headers: UA })).arrayBuffer());

// Cut to the disc: the rows and columns with any surface on them.
const { data, info: size } = await sharp(jpeg).greyscale().raw().toBuffer({ resolveWithObject: true });
let [left, top, right, bottom] = [size.width, size.height, -1, -1];
for (let y = 0; y < size.height; y++) {
  for (let x = 0; x < size.width; x++) {
    if (data[y * size.width + x] < 24) continue;
    left = Math.min(left, x); right = Math.max(right, x);
    top = Math.min(top, y); bottom = Math.max(bottom, y);
  }
}
const side = Math.max(right - left, bottom - top) + 1;
const disc = await sharp(jpeg).greyscale()
  .extract({ left, top, width: Math.min(side, size.width - left), height: Math.min(side, size.height - top) })
  .resize(SIZE, SIZE, { fit: "fill", kernel: "lanczos3" })
  .raw().toBuffer();

await writeFile(out, `// Generated by tools/moon/build.mjs from NASA's LRO near-side mosaic (public domain,
// ${info.descriptionurl}). Do not edit.
// ${SIZE} × ${SIZE} greyscale, 0 black … 255 white, the disc touching all four edges.

export const TEXTURE_SIZE = ${SIZE};
export const TEXTURE = "${disc.toString("base64")}";
`);
console.log(`moon: ${SIZE} × ${SIZE} from ${right - left + 1} × ${bottom - top + 1}, ${licence}`);
