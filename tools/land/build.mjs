// The world's land as a 720 × 360 bitmap (half a degree a pixel, north up,
// from 180° W), for globes drawn when a project compiles. From Natural Earth's
// 1:110m land, which is in the public domain. Run by hand; the output is
// committed: node land/build.mjs

import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SOURCE = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_110m_land.geojson";
const W = 720;
const H = 360;

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.resolve(here, "../../app/src/extensions/iss/land.ts");

const geo = await (await fetch(SOURCE)).json();
const rings = [];
for (const f of geo.features) {
  const g = f.geometry;
  const polys = g.type === "Polygon" ? [g.coordinates] : g.type === "MultiPolygon" ? g.coordinates : [];
  for (const poly of polys) for (const ring of poly) rings.push(ring);
}

// Even-odd scanlines through every ring at each pixel row's centre: holes (lakes) stay water.
const bits = new Uint8Array((W / 8) * H);
for (let y = 0; y < H; y++) {
  const lat = 90 - (y + 0.5) * (180 / H);
  const xs = [];
  for (const ring of rings) {
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
      const [x1, y1] = ring[j];
      const [x2, y2] = ring[i];
      if ((y1 > lat) !== (y2 > lat)) xs.push(x1 + ((lat - y1) / (y2 - y1)) * (x2 - x1));
    }
  }
  xs.sort((a, b) => a - b);
  for (let k = 0; k + 1 < xs.length; k += 2) {
    const from = Math.max(0, Math.ceil((xs[k] + 180) * (W / 360) - 0.5));
    const to = Math.min(W - 1, Math.floor((xs[k + 1] + 180) * (W / 360) - 0.5));
    for (let x = from; x <= to; x++) bits[y * (W / 8) + (x >> 3)] |= 0x80 >> (x & 7);
  }
}

const base64 = Buffer.from(bits).toString("base64");
await writeFile(out, `// Generated by tools/land/build.mjs from Natural Earth 1:110m land (public domain). Do not edit.
// ${W} × ${H}, half a degree a pixel, north up from 90° N, east from 180° W; MSB first.

export const LAND_WIDTH = ${W};
export const LAND_HEIGHT = ${H};
export const LAND = "${base64}";
`);
console.log(`land.ts  ${W}×${H}  ${base64.length} chars`);
